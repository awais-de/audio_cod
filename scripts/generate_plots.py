    ax1.set_title('Bitrate tracks signal complexity', fontsize=11, fontweight='bold')
    ax1.set_xlim(0, 10.5)
    ax1.legend(fontsize=8)
    ax1.grid(True, axis='x', alpha=0.25)
    ax1.spines['top'].set_visible(False)
    ax1.spines['right'].set_visible(False)

    # Right: STOI
    bars2 = ax2.barh(labels, stois, color=colors, alpha=0.85,
                     edgecolor='white', linewidth=0.5)
    for bar, v in zip(bars2, stois):
        xpos = max(bar.get_width(), 0) + 0.01
