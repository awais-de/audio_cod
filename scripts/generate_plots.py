    labels = [d[0] for d in OOD_DATA]
    kbps   = [d[1] for d in OOD_DATA]
    stois  = [d[2] for d in OOD_DATA]
    is_sp  = [d[3] for d in OOD_DATA]

    colors = [BLUE if sp else ORANGE for sp in is_sp]

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4.5))

    # Left: bitrate
    bars = ax1.barh(labels, kbps, color=colors, alpha=0.85,
                    edgecolor='white', linewidth=0.5)
    ax1.axvline(x=9.6, color='gray', linestyle='--', linewidth=1.2, label='9.6 kbps cap')
    for bar, v in zip(bars, kbps):
        ax1.text(bar.get_width() + 0.1, bar.get_y() + bar.get_height()/2,
                 f'{v:.2f}', va='center', ha='left', fontsize=8.5)
