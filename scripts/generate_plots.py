# 1. Entropy-PESQ scatter (main paper figure)
# ---------------------------------------------------------------------------

def plot_entropy_pesq_scatter(out_dir):
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(7, 5))

    marker_style = {'C': 'o', 'D': 's', 'D-VAE': 'D', 'E': '^', 'F': 'v', 'G': '*'}
    label_offset = {
        'C':     ( 6,  4),
        'D':     ( 6, -12),
        'D-VAE': (-72,  4),
        'E':     ( 6,  4),
        'F':     ( 6, -12),
        'G':     ( 6,  4),
    }

    # Dashed trend line through non-VAE phases
    non_vae = [p for p in PHASES if p != 'D-VAE']
    ax.plot(
        [PHASE_DATA[p]['entropy'] for p in non_vae],
        [PHASE_DATA[p]['pesq']   for p in non_vae],
        '--', color=BLUE, alpha=0.25, linewidth=1.5, zorder=2,
    )

    for phase in PHASES:
        d = PHASE_DATA[phase]
        is_vae = phase == 'D-VAE'
        color  = CRIMSON if is_vae else BLUE
        size   = 200 if phase == 'G' else (180 if is_vae else 100)
        ax.scatter(
            d['entropy'], d['pesq'],
            c=color, marker=marker_style[phase],
            s=size, zorder=5, edgecolors='white', linewidths=0.6,
        )
        ax.annotate(
            f'Phase {phase}',
            (d['entropy'], d['pesq']),
            textcoords='offset points',
            xytext=label_offset[phase],
            fontsize=9,
            color=CRIMSON if is_vae else BLUE,
            fontweight='bold' if phase in ('G', 'D-VAE') else 'normal',
        )

    ax.set_xlabel('Mean latent entropy per dimension H(d)  (bits)', fontsize=11)
    ax.set_ylabel('PESQ-WB', fontsize=11)
    ax.set_title('Entropy–Quality Tension Across Training Phases',
                 fontsize=12, fontweight='bold')
    ax.grid(True, alpha=0.25)

    ax.text(0.03, 0.97,
            'more compressible  ←',
            transform=ax.transAxes, fontsize=8, color=GRAY,
            va='top', ha='left', style='italic')
    ax.text(0.97, 0.97,
            '→  higher quality',
            transform=ax.transAxes, fontsize=8, color=GRAY,
            va='top', ha='right', style='italic')

    from matplotlib.lines import Line2D
    legend_elements = [
        Line2D([0],[0], marker='o', color='w', markerfacecolor=BLUE,
               markersize=8, label='Training phases (C, D, E, F, G)'),
        Line2D([0],[0], marker='D', color='w', markerfacecolor=CRIMSON,
               markersize=8, label='Phase D-VAE  (KL regularisation)'),
    ]
    ax.legend(handles=legend_elements, fontsize=9, loc='lower right')

    _save(fig, out_dir / 'entropy_pesq_scatter.png')


