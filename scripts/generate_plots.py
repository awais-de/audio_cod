# ---------------------------------------------------------------------------

def plot_speaker_probe_recall(out_dir):
    import matplotlib.pyplot as plt

    speakers = [s[0] for s in SPEAKER_RECALL]
    recalls  = [s[1] for s in SPEAKER_RECALL]
    mean_acc = 35.8
    chance   = 3.125  # 1/32

    colors = [CRIMSON if r == 0.0 else (GREEN if r == 100.0 else BLUE) for r in recalls]

    fig, ax = plt.subplots(figsize=(10, 6))
    bars = ax.barh(speakers, recalls, color=colors, alpha=0.85,
                   edgecolor='white', linewidth=0.5)

    ax.axvline(x=chance,   color='gray',   linestyle='--', linewidth=1.2,
               label=f'Chance ({chance:.1f}%)')
    ax.axvline(x=mean_acc, color=ORANGE,   linestyle='-',  linewidth=1.5,
               label=f'Mean accuracy ({mean_acc:.1f}%)')

    for bar, v in zip(bars, recalls):
        ax.text(bar.get_width() + 0.5, bar.get_y() + bar.get_height()/2,
                f'{v:.0f}%', va='center', ha='left', fontsize=8)

    ax.set_xlabel('Recall (%)', fontsize=11)
    ax.set_ylabel('Speaker ID', fontsize=11)
    ax.set_title('Speaker Identity Linear Probe — Per-Speaker Recall\n'
                 '(32 speakers, 3s clips, frozen Phase G encoder, 32-dim mean-pooled latent)',
                 fontsize=11, fontweight='bold')
    ax.set_xlim(0, 115)
    ax.grid(True, axis='x', alpha=0.25)
    ax.spines['top'].set_visible(False)
    ax.spines['right'].set_visible(False)
    ax.legend(fontsize=9, loc='lower right')

    from matplotlib.patches import Patch
    extra = [
        Patch(facecolor=GREEN,  label='100% recall (perfectly separable)'),
        Patch(facecolor=BLUE,   label='Partial recall'),
        Patch(facecolor=CRIMSON, label='0% recall (confused with others)'),
    ]
    ax.legend(handles=extra + ax.get_legend_handles_labels()[0][2:],
              fontsize=8, loc='lower right')

    plt.tight_layout()
    _save(fig, out_dir / 'speaker_probe_recall.png')


